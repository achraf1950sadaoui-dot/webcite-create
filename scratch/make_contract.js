const fs = require("fs");
const {
  Document, Packer, Paragraph, TextRun, AlignmentType, BorderStyle,
} = require("docx");

const FONT = "Arial";

// Helper: RTL paragraph
function p(children, opts = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: opts.alignment || AlignmentType.JUSTIFIED,
    spacing: { after: opts.after != null ? opts.after : 140, line: 300 },
    border: opts.border,
    children,
  });
}

// Helper: run
function r(text, opts = {}) {
  return new TextRun({
    text,
    rightToLeft: true,
    font: FONT,
    size: opts.size || 22, // half-points => 11pt
    bold: opts.bold || false,
  });
}

// Article: bold label + normal body in same paragraph
function article(label, body) {
  return p([r(label + " ", { bold: true }), r(body)]);
}

